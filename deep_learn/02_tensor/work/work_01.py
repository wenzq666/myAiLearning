# 在一个典型的训练循环中，为什么每次在进行自动微分(backward())之前，都需要执行梯度清零？如果不执行会有什么后果？
# 求导前必做 原因：torch会对多次迭代的导数自动累加 , 如果不执行则会把前面的结果累加进行后面的梯度计算




# 我们希望通过梯度下降法，寻找函数 $y = (x - 5)^2$ 的极小值点（显然，当 $x = 5$ 时，$y$ 取得极小值）。
# 请你在下方代码的指定位置，补全**梯度清零**和**反向传播**的代码。
# 1. 初始化自变量 x，初始值设为 10.0，并设置 requires_grad=True
x = torch.tensor(10.0, requires_grad=True, dtype=torch.float32)

# 学习率
learning_rate = 0.1

# 进行 100 次迭代更新
for i in range(100):
    # 2. 前向传播：计算当前的函数值（损失值）
    y = (x - 5) ** 2

    # 3. 【空白 1】梯度清零
    # 提示：如果 x 的梯度不为空（x.grad is not None），需要调用相应的方法将 x 的梯度清零，避免梯度累加。
    if x.grad is not None:
        # 请在下方填写代码：
        x.grad.zero_()


    # 4. 【空白 2】反向传播
    # 提示：通过损失值 y 启动自动微分，计算相对于 x 的梯度。
    # 请在下方填写代码：
    y.backward()


    # 5. 更新参数
    x.data = x.data - learning_rate * x.grad

# 输出最终的迭代结果
print(f"经过100次迭代后，x 的值是: {x.item():.4f} (期望值接近 5.0)")






